import type { Block } from "./blocks";
import { builds, formatMln, type BudgetBuild } from "./builds";

export interface Post {
  slug: string;
  /** H1 и заголовок в выдаче (до ~60 символов). */
  title: string;
  /** Description для поисковиков (до ~155 символов). */
  description: string;
  /** Короткий анонс для карточки. */
  excerpt: string;
  published: string; // YYYY-MM-DD
  updated: string; // YYYY-MM-DD
  read: string;
  body: Block[];
}

const YEAR = 2026;
const PUBLISHED = "2026-10-05";

const partsTable = (b: BudgetBuild): Block => ({
  type: "table",
  head: ["Комплектующее", "Что ставим"],
  rows: [...b.parts.map((p) => [p.part, p.pick]), ["Плата, корпус, охлаждение", "Под выбранный процессор, с хорошим продувом"]],
});

const priceNote: Block = {
  type: "note",
  text: "Цены на комплектующие меняются каждую неделю, особенно на видеокарты и память. Пришлите нам бюджет — составим смету по сегодняшним ценам и покажем, где можно сэкономить.",
};

/** Общая часть статей «Игровой ПК за N млн»; у каждой своё вступление и советы. */
function budgetPost(b: BudgetBuild, intro: string[], tips: string[], upgrade: string): Post {
  const others = builds.filter((x) => x.budget !== b.budget);
  return {
    slug: b.slug,
    title: `Игровой ПК за ${formatMln(b.budget)} в ${YEAR}: лучшая сборка`,
    description: `Какой игровой компьютер собрать за ${formatMln(b.budget)} в ${YEAR} году: конфигурация, для каких игр подойдёт, на чём можно сэкономить. Сборка на заказ.`,
    excerpt: `${b.target}. ${b.games}.`,
    published: PUBLISHED,
    updated: PUBLISHED,
    read: "5 мин",
    body: [
      ...intro.map((text): Block => ({ type: "p", text })),
      { type: "h2", text: `Конфигурация за ${formatMln(b.budget)}` },
      partsTable(b),
      priceNote,
      { type: "h2", text: "Для каких игр и задач" },
      { type: "p", text: `${b.games}.` },
      { type: "h2", text: "На что обратить внимание" },
      { type: "ul", items: tips },
      { type: "h2", text: "Что можно улучшить потом" },
      { type: "p", text: upgrade },
      { type: "h2", text: "Другие бюджеты" },
      {
        type: "ul",
        items: others.map((x) => `[Игровой ПК за ${formatMln(x.budget)}](/blog/${x.slug}) — ${x.target}`),
      },
      {
        type: "p",
        text: "Хотите такую сборку? Мы [соберём компьютер](/sborka-kompyutera) под ваш бюджет, проверим под нагрузкой при вас и выдадим с гарантией 30 дней.",
      },
    ],
  };
}

